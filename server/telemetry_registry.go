const (
	TelemetryIngressNative     = "native"
	TelemetryIngressStandalone = "standalone"
	TelemetryIngressUnknown    = "unknown"
	TelemetryIngressMixed      = "mixed"
)

func ingressRoleIndex(role string) int {
	switch role {
	case TelemetryIngressNative:
		return 0
	case TelemetryIngressStandalone:
		return 1
	case TelemetryIngressMixed:
		return 3
	default:
		return 2
	}
}

func ingressRoleForListener(sidecar bool) string {
	if sidecar {
		return TelemetryIngressStandalone
	}
	return TelemetryIngressNative
}

