type TelemetryConfig struct {
	Enabled            bool
	SnapshotInterval   time.Duration
	MaxActiveSessions  int
	MaxEvents          int
	CloseGrace         time.Duration
	HMACSecret         []byte
	AccountingPath     string
	AccountingTimezone string
	AccountingInterval time.Duration
}

// TelemetryOptions is intentionally disabled by default and contains no
// secret-bearing field. The process-local HMAC secret is generated by the
// registry and is never loaded from or written to config.
type TelemetryOptions struct {
	Enabled            bool     `json:"enabled"`
	Listen             string   `json:"listen"`
	SnapshotInterval   Duration `json:"snapshot_interval"`
	MaxActiveSessions  int      `json:"max_active_sessions"`
	MaxEvents          int      `json:"max_events"`
	CloseGrace         Duration `json:"close_grace"`
	AccountingPath     string   `json:"accounting_path"`
	AccountingTimezone string   `json:"accounting_timezone"`
	AccountingInterval Duration `json:"accounting_interval"`
}

func (o TelemetryOptions) registryConfig() TelemetryConfig {
	return TelemetryConfig{
		Enabled:            o.Enabled,
		SnapshotInterval:   o.SnapshotInterval.Time(),
		MaxActiveSessions:  o.MaxActiveSessions,
		MaxEvents:          o.MaxEvents,
		CloseGrace:         o.CloseGrace.Time(),
		AccountingPath:     o.AccountingPath,
		AccountingTimezone: o.AccountingTimezone,
		AccountingInterval: o.AccountingInterval.Time(),
	}
}

func (o *TelemetryOptions) NormalizeAndValidate() error {
	if !o.Enabled {
		return nil
	}
	if o.AccountingTimezone == "" {
		o.AccountingTimezone = "UTC"
	}
	if o.AccountingInterval.Time() <= 0 {
		o.AccountingInterval = Duration(10 * time.Second)
	}
	if _, err := time.LoadLocation(o.AccountingTimezone); err != nil {
		return fmt.Errorf("invalid telemetry.accounting_timezone %q: %w", o.AccountingTimezone, err)
	}
	if o.Listen == "" {
		o.Listen = "127.0.0.1:24500"
	}
	host, portText, err := net.SplitHostPort(o.Listen)
	if err != nil {
		return fmt.Errorf("invalid telemetry.listen %q", o.Listen)
	}
	if host != "127.0.0.1" && host != "::1" {
		return fmt.Errorf("telemetry.listen must use literal loopback 127.0.0.1 or ::1")
	}
	port, err := strconv.Atoi(portText)
	if err != nil || port < 0 || port > 65535 {
		return fmt.Errorf("invalid telemetry.listen port %q", portText)
	}
	return nil
}

